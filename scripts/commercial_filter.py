MIN_VOL = 300      # 월 검색량 최소치


def _num(v, default=0):
    if isinstance(v, (int, float)):
        return int(v)
    try:
        return int(str(v).replace("<", "").replace(",", "").strip())
    except Exception:
        return default


def is_commercial(kw, ads=None, cat=""):
    """상업성 키워드면 True. ads=plclAdCnt(월평균 노출 광고수)."""
    kw = (kw or "").strip()
    if len(kw) < 2 or len(kw) > 25:
        return False
    if not _HANGUL.search(kw):
        return False
    if _TAIL_INFO.search(kw):
        return False
    block = _BLOCK_TRAVEL if cat.startswith("여행") else _BLOCK
    if block.search(kw):
        return False
    if ads is not None and _num(ads, 0) < MIN_ADS:
        return False
    return True


def filter_rows(rows, cat=""):
    """[{kw, vol, ads, ...}] → 상업성 통과분만"""
    return [r for r in rows if is_commercial(r.get("kw"), r.get("ads"), cat)]
